void ASAHIOperand::print(raw_ostream &OS) const {
    switch (Kind) {
    case k_Immediate:
      OS << *getImm();
      break;
    case k_Token:
      OS << "'" << getToken() << "'";
      break;
    case k_Register:
      OS << "<register " << getReg() << ">";
      break;
    }
}


ParseStatus ASAHIAsmParser::parseImmediate(OperandVector &Operands) {
    /*

    For immediate any one of the below token is a valid value

    | Token Kind | Example |
    | ---------- | ------- |
    | Integer    | `42`    |
    | Minus      | `-5`    |
    | Plus       | `+7`    |
    | Identifier | `label` |
    | LParen     | `(4+5)` |

    addi r1, 42

    or

    addi r1, label+8

    or

    addi r1, -5

    getLexer().getKind() tries to match that
    
    */
    switch (getLexer().getKind()) {
    default:
      return ParseStatus::NoMatch;
    case AsmToken::LParen:
    case AsmToken::Minus:
    case AsmToken::Plus:
    case AsmToken::Integer:
    case AsmToken::String:
    case AsmToken::Identifier:
      break;
    }

    const MCExpr *IdVal;
    SMLoc S = getLoc();

    /*
    Evaluate the expression

    42 --> MCConstantExpr(42)
    label + 8 --->  MCBinaryExpr(
                       Symbol(label),
                       Constant(8)
                    )
    */
    bool HasError = getParser().parseExpression(IdVal);
    if (HasError)
      return ParseStatus::Failure;
    // because after parsing, lexer has advanced past the operand we do -1.
    SMLoc E = SMLoc::getFromPointer(S.getPointer() - 1);
    Operands.push_back(ASAHIOperand::createImm(IdVal, S, E));

    return ParseStatus::Success;
}

ParseStatus ASAHIAsmParser::parseRegister(OperandVector &Operands) {
    SMLoc S = getLoc();
    SMLoc E = SMLoc::getFromPointer(S.getPointer() - 1);

    switch (getLexer().getKind()) {
    default:
      return ParseStatus::NoMatch;
    case AsmToken::Identifier:
      StringRef Name = getLexer().getTok().getIdentifier();
      unsigned RegNo = MatchRegisterName(Name);

      if (RegNo == 0)
        return ParseStatus::NoMatch;

      getLexer().Lex();
      Operands.push_back(ASAHIOperand::createReg(RegNo, S, E));
    }
  
    return ParseStatus::Success;
}

bool ASAHIAsmParser::parseInstruction(ParseInstructionInfo &Info,
                                      StringRef Name, SMLoc NameLoc,
                                      OperandVector &Operands) {
    /*
    This function parses an entire assembly instruction line into a list of operands.

    add r1, r2, 42

    becomes

    Operands:
      Token("add")
      Register(r1)
      Register(r2)
      Immediate(42)

    Overall structure

    text
      ↓
    lexer tokens
      ↓
    parser operands
      ↓
    instruction matcher
      ↓
    MCInst

    This function
    lexer tokens → parser operands

    Suppose,
        add r1, r2, 42
    then,
        Name = "add"
    
    OperandVector takes is a vector of operands.
    */

    Operands.push_back(ASAHIOperand::createToken(Name, NameLoc));

    // Keep parsing operands until end of line.
    while (!getLexer().is(AsmToken::EndOfStatement)) {
        // Attempt to parse token as register
        if (parseRegister(Operands).isSuccess())
          continue;

        // consume ,
        if (getLexer().is(AsmToken::Comma)) {
            getLexer().Lex();
            continue;
        }

        // Attempt to parse token as an immediate
        if (parseImmediate(Operands).isSuccess())
            continue;
      
        SMLoc Loc = getLexer().getLoc();
        return Error(Loc, "unexpected token");
    }

    // Consume the EndOfStatement.
    getParser().Lex();
    return false;
}

bool ASAHIAsmParser::parseRegister(MCRegister &Reg, SMLoc &StartLoc, SMLoc &EndLoc) {
    /*
    MCTargetAsmParser needs these methods to be overriden, even thought they are not
    used in the above parseInstruction which build ASAHIOperands(which are basically
    MCParsedAsmOperand).

    It just answers current token → which MCRegister?

    parseRegister(OperandVector)
      → parse register as an instruction operand
      → push ASAHIOperand

    parseRegister(MCRegister&)
      → parse register as a raw MCRegister
      → no ASAHIOperand

    */
    if(!tryParseRegister(Reg, StartLoc, EndLoc).isSuccess()) {
        return Error(StartLoc, "invalid Register name");
    }

    return false;
}

ParseStatus ASAHIAsmParser::tryParseRegister(MCRegister &Reg, SMLoc &StartLoc,
                                             SMLoc &EndLoc) {
    // Get the current token, and try parse it to see if its a register
    const AsmToken &Tok = getParser().getTok();
    StartLoc = Tok.getLoc();
    EndLoc = Tok.getEndLoc();

    // Gets the current token being processed, often same as the parser.getTok()
    StringRef Name = getLexer().getTok().getIdentifier();
    Reg = MatchRegisterName(Name);

    if (Reg != ASAHI::NoRegister) {
        getParser().Lex(); // Eat identifier token.
        return ParseStatus::Success;
    }

    return ParseStatus::NoMatch;
}

bool ASAHIAsmParser::matchAndEmitInstruction(SMLoc IDLoc, unsigned &Opcode,
                                             OperandVector &Operands,
                                             MCStreamer &Out,
                                             uint64_t &ErrorInfo,
                                             bool MatchingInlineAsm) {
    /*
    parseInstruction builds ASAHIOperands.
    Because parseInstruction only gives you this: 
        Operands [Token("add"), Reg(r1), Reg(r2)]

    But LLVM still needs to decide: Which real opcode is this?
        ADDrr?
        ADDri?
        .
        .
    matchAndEmitInstruction uses the TableGen-generated matcher to convert those operands into an 
    MCInst.

    MatchInstructionImpl is generated from TableGen. It compares the parsed ASAHIOperands 
    against your instruction AsmStrings/patterns($dst, $src0 ..)

    Printing is separate; it is handled by the InstPrinter when disassembling or printing MCInsts as assembly.
    */
    MCInst Inst;
    SMLoc ErrorLoc;

    switch (MatchInstructionImpl(Operands, Inst, ErrorInfo, MatchingInlineAsm)) {
    default:
        break;
    case Match_Success:
        Inst.setLoc(IDLoc);
        Out.emitInstruction(Inst, getSTI());
        return false;
    case Match_MissingFeature:
        return Error(IDLoc, "instruction use requires an option to be enabled");
    case Match_MnemonicFail:
        return Error(IDLoc, "unrecognized instruction mnemonic");
    case Match_InvalidOperand:
        ErrorLoc = IDLoc;
        
        if (ErrorInfo != ~0U) {
            if (ErrorInfo >= Operands.size())
                return Error(ErrorLoc, "too few operands for instruction");

        ErrorLoc = ((ASAHIOperand &)*Operands[ErrorInfo]).getStartLoc();

        if (ErrorLoc == SMLoc())
            ErrorLoc = IDLoc;
        }

        return Error(ErrorLoc, "invalid operand for instruction");
    }

  llvm_unreachable("Unknown match type detected!");
}

