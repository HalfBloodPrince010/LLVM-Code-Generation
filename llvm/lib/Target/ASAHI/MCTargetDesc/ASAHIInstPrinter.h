#ifndef LLVM_LIB_TARGET_ASAHI_MCTARGETDESC_ASAHIINSTPRINTER_H
#define LLVM_LIB_TARGET_ASAHI_MCTARGETDESC_ASAHIINSTPRINTER_H

#include "MCTargetDesc/ASAHIMCTargetDesc.h"
#include "llvm/ADT/StringRef.h"
#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class ASAHIInstPrinter: public MCInstPrinter {
private:
    // Operand printer.
    void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
    void printImm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
    void printRegName(raw_ostream &OS, MCRegister Reg) override;

public:
    ASAHIInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII, const MCRegisterInfo &MRI);

    void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;
    
    // Autogenerated by tblgen.
    std::pair<const char *, uint64_t>
    getMnemonic(const MCInst &MI) const override;
  
    virtual void printInstruction(const MCInst *MI, uint64_t Address,
        raw_ostream &O);
    
    virtual bool printAliasInstr(const MCInst *MI, uint64_t Address,
        raw_ostream &O);
    
    static const char *getRegisterName(MCRegister Reg);
};

} // end llvm namespace


#endif // LLVM_LIB_TARGET_ASAHI_MCTARGETDESC_ASAHIINSTPRINTER_H